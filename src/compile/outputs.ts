import { randomBytes } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, realpathSync, renameSync, rmdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, sep } from 'node:path';
import { compareText } from './model.js';
import { AGENTS_BEGIN, AGENTS_END, GENERATED_MARK } from './render.js';

export const SKILL_ROOTS = ['.agents/skills', '.claude/skills', '.gemini/skills'] as const;
export const AGENTS_FILE = 'AGENTS.md';

export type Output = { path: string; content: string };
export type AgentsState = { kind: 'current' } | { kind: 'write'; next: string } | { kind: 'unmanaged' };
export type OutputDiff = { write: Output[]; remove: string[]; agents: AgentsState };

export class HumanFileError extends Error {
  override name = 'HumanFileError';
}

const lf = (s: string) => s.replace(/\r\n/g, '\n');

function readText(root: string, path: string): string | null {
  const full = join(root, path);
  if (!existsSync(full) || !statSync(full).isFile()) return null;
  return readFileSync(full, 'utf8');
}

function exists(full: string): boolean {
  try {
    lstatSync(full);
    return true;
  } catch {
    return false;
  }
}

/**
 * Where a write to `path` really lands, following links. A link (on the file
 * or on a parent folder) that leaves the repository is refused.
 */
function realTarget(root: string, path: string): string {
  const full = join(root, path);
  let probe = full;
  while (!exists(probe)) probe = dirname(probe);
  const real = realpathSync.native(probe);
  const rel = relative(realpathSync.native(root), real);
  if (rel === '..' || rel.startsWith(`..${sep}`) || isAbsolute(rel)) {
    throw new HumanFileError(`refusing to write ${path}: it links outside the repository`);
  }
  return probe === full ? real : join(real, relative(probe, full));
}

/** Temp file + rename on the link's target, so a symlinked file stays a link. */
function writeAtomic(root: string, path: string, content: string): void {
  const target = realTarget(root, path);
  mkdirSync(dirname(target), { recursive: true });
  const tmp = `${target}.${process.pid}.${randomBytes(4).toString('hex')}.tmp`;
  writeFileSync(tmp, content, { encoding: 'utf8', flag: 'wx' });
  renameSync(tmp, target);
}

/** Generated files keelson may find on disk: the index levels and every keelson-* skill. */
function candidates(root: string): string[] {
  const found = ['.keelson/index.md'];
  const levels = join(root, '.keelson', 'index');
  if (existsSync(levels)) {
    for (const name of readdirSync(levels)) if (name.endsWith('.md')) found.push(`.keelson/index/${name}`);
  }
  for (const skills of SKILL_ROOTS) {
    const dir = join(root, skills);
    if (!existsSync(dir)) continue;
    for (const name of readdirSync(dir)) if (name.startsWith('keelson-')) found.push(`${skills}/${name}/SKILL.md`);
  }
  return found;
}

type Block = { kind: 'absent' } | { kind: 'unmanaged'; text: string } | { kind: 'managed'; text: string; begin: number; end: number };

function readAgents(root: string): Block {
  const text = readText(root, AGENTS_FILE);
  if (text === null) return { kind: 'absent' };
  const begin = text.indexOf(AGENTS_BEGIN);
  const end = text.indexOf(AGENTS_END);
  if (begin < 0 && end < 0) return { kind: 'unmanaged', text };
  const twice = text.indexOf(AGENTS_BEGIN, begin + 1) >= 0 || text.indexOf(AGENTS_END, end + 1) >= 0;
  if (begin < 0 || end < 0 || twice || end < begin) throw new HumanFileError('AGENTS.md has malformed keelson markers; fix them by hand');
  return { kind: 'managed', text, begin, end: end + AGENTS_END.length };
}

/** The block in the file's own line endings, so a CRLF file stays CRLF. */
function inEol(text: string, block: string): { eol: string; block: string } {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  return { eol, block: eol === '\r\n' ? block.replace(/\n/g, '\r\n') : block };
}

/**
 * Plans the writes without touching disk. Every generated path is checked
 * before anything is planned, so a human file at one of them stops the whole run.
 */
export function diffOutputs(root: string, files: Output[], agentsBlock: string): OutputDiff {
  const write: Output[] = [];
  for (const f of [...files, { path: AGENTS_FILE, content: '' }]) realTarget(root, f.path);
  for (const f of files) {
    const current = readText(root, f.path);
    if (current === null) {
      if (existsSync(join(root, f.path))) throw new HumanFileError(`refusing to overwrite ${f.path}: it is not a file written by keelson`);
      write.push(f);
      continue;
    }
    if (!current.includes(GENERATED_MARK)) throw new HumanFileError(`refusing to overwrite ${f.path}: it was not generated by keelson`);
    if (lf(current) !== f.content) write.push(f);
  }

  // Compare real paths: with linked skill roots one file is reachable through several paths.
  const planned = new Set(files.map((f) => realTarget(root, f.path)));
  const seen = new Set<string>();
  const remove = candidates(root)
    .sort(compareText)
    .filter((p) => readText(root, p)?.includes(GENERATED_MARK) === true)
    .filter((p) => {
      const real = realTarget(root, p);
      if (planned.has(real) || seen.has(real)) return false;
      seen.add(real);
      return true;
    });

  const block = readAgents(root);
  let agents: AgentsState;
  if (block.kind === 'absent') agents = { kind: 'write', next: `${agentsBlock}\n` };
  else if (block.kind === 'unmanaged') agents = { kind: 'unmanaged' };
  else {
    const next = block.text.slice(0, block.begin) + inEol(block.text, agentsBlock).block + block.text.slice(block.end);
    agents = lf(next) === lf(block.text) ? { kind: 'current' } : { kind: 'write', next };
  }
  return { write, remove, agents };
}

export function applyOutputs(root: string, diff: OutputDiff): void {
  for (const f of diff.write) writeAtomic(root, f.path, f.content);
  for (const p of diff.remove) {
    const full = realTarget(root, p);
    if (!existsSync(full)) continue;
    unlinkSync(full);
    const dir = dirname(full);
    if (readdirSync(dir).length === 0) rmdirSync(dir);
  }
  if (diff.agents.kind === 'write') writeAtomic(root, AGENTS_FILE, diff.agents.next);
}

/**
 * Appends the keelson block to a human-written AGENTS.md and returns the added
 * lines. Called only on an explicit request from a person; returns '' when the
 * file is absent or already has a block, which a normal compile handles.
 */
export function adoptAgentsMd(root: string, agentsBlock: string): string {
  const current = readAgents(root);
  if (current.kind !== 'unmanaged') return '';
  const { eol, block } = inEol(current.text, agentsBlock);
  const lead = current.text.endsWith('\n') ? '' : eol;
  const added = `${lead}${eol}${block}${eol}`;
  writeAtomic(root, AGENTS_FILE, current.text + added);
  const shown = lf(added).split('\n');
  shown.pop();
  return shown.map((l) => `+${l}`).join('\n') + '\n';
}
